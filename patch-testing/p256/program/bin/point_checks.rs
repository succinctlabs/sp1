#![no_main]
sp1_zkvm::entrypoint!(main);

use p256::ecdsa::{
    signature::{Signer, Verifier},
    Signature, SigningKey, VerifyingKey,
};
use p256::elliptic_curve::sec1::{FromEncodedPoint, ToEncodedPoint};

const P256_G_X: [u8; 32] = [
    0x6b, 0x17, 0xd1, 0xf2, 0xe1, 0x2c, 0x42, 0x47, 0xf8, 0xbc, 0xe6, 0xe5, 0x63, 0xa4, 0x40, 0xf2,
    0x77, 0x03, 0x7d, 0x81, 0x2d, 0xeb, 0x33, 0xa0, 0xf4, 0xa1, 0x39, 0x45, 0xd8, 0x98, 0xc2, 0x96,
];
const P256_G_Y: [u8; 32] = [
    0x4f, 0xe3, 0x42, 0xe2, 0xfe, 0x1a, 0x7f, 0x9b, 0x8e, 0xe7, 0xeb, 0x4a, 0x7c, 0x0f, 0x9e, 0x16,
    0x2b, 0xce, 0x33, 0x57, 0x6b, 0x31, 0x5e, 0xce, 0xcb, 0xb6, 0x40, 0x68, 0x37, 0xbf, 0x51, 0xf5,
];
const P256_7G_X: [u8; 32] = [
    0x8e, 0x53, 0x3b, 0x6f, 0xa0, 0xbf, 0x7b, 0x46, 0x25, 0xbb, 0x30, 0x66, 0x7c, 0x01, 0xfb, 0x60,
    0x7e, 0xf9, 0xf8, 0xb8, 0xa8, 0x0f, 0xef, 0x5b, 0x30, 0x06, 0x28, 0x70, 0x31, 0x87, 0xb2, 0xa3,
];
const P256_7G_Y: [u8; 32] = [
    0x73, 0xeb, 0x1d, 0xbd, 0xe0, 0x33, 0x18, 0x36, 0x6d, 0x06, 0x9f, 0x83, 0xa6, 0xf5, 0x90, 0x00,
    0x53, 0xc7, 0x36, 0x33, 0xcb, 0x04, 0x1b, 0x21, 0xc5, 0x5e, 0x1a, 0x86, 0xc1, 0xf4, 0x00, 0xb4,
];
const P256_MODULUS: [u8; 32] = [
    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
];
const OPPOSITE_SCALAR: [u8; 32] = [
    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xbc, 0xe6, 0xfa, 0xad, 0xa7, 0x17, 0x9e, 0x84, 0xf3, 0xb9, 0xca, 0xc2, 0xfc, 0x63, 0x25, 0x50,
];
pub fn main() {
    let mut compact = [0u8; 33];
    compact[0] = 0x05;
    compact[1..].copy_from_slice(&P256_G_X);
    let encoded = p256::EncodedPoint::from_bytes(compact).unwrap();
    let point =
        Option::<p256::AffinePoint>::from(p256::AffinePoint::from_encoded_point(&encoded)).unwrap();
    let uncompressed = point.to_encoded_point(false);
    assert_eq!(&uncompressed.as_bytes()[1..33], &P256_G_X);
    assert_eq!(&uncompressed.as_bytes()[33..], &P256_G_Y);

    let signing_key = SigningKey::from_bytes((&OPPOSITE_SCALAR).into()).unwrap();
    let message = b"P-256 point encoding check";
    let signature: Signature = signing_key.sign(message);
    let verifying_key = VerifyingKey::from_sec1_bytes(&compact).unwrap();
    assert!(verifying_key.verify(message, &signature).is_err());

    compact[1..].copy_from_slice(&P256_7G_X);
    let encoded = p256::EncodedPoint::from_bytes(compact).unwrap();
    let point =
        Option::<p256::AffinePoint>::from(p256::AffinePoint::from_encoded_point(&encoded)).unwrap();
    let uncompressed = point.to_encoded_point(false);
    assert_eq!(&uncompressed.as_bytes()[1..33], &P256_7G_X);
    assert_eq!(&uncompressed.as_bytes()[33..], &P256_7G_Y);

    compact[1..].copy_from_slice(&P256_MODULUS);
    let encoded = p256::EncodedPoint::from_bytes(compact).unwrap();
    assert!(bool::from(p256::AffinePoint::from_encoded_point(&encoded).is_none()));

    compact[1..].fill(0);
    compact[32] = 1;
    let encoded = p256::EncodedPoint::from_bytes(compact).unwrap();
    assert!(bool::from(p256::AffinePoint::from_encoded_point(&encoded).is_none()));
    sp1_zkvm::io::commit(&true);
}
